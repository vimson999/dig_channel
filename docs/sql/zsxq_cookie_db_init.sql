-- ZSXQ cookie account DB bootstrap.
-- Execute with a PostgreSQL role that can CREATE TABLE in schema public.
--
-- Schema + grants only:
--   psql "$DATABASE_URL" -f docs/sql/zsxq_cookie_db_init.sql
--
-- Schema + one encrypted cookie account + default bindings:
--   psql "$DATABASE_URL" \
--     -v seed_cookie_account=true \
--     -v cookie_account_name='main zsxq account' \
--     -v cookie_purpose=both \
--     -v cookie_group_id='28888112822211' \
--     -v encrypted_cookie='gAAAAA...' \
--     -v cookie_fingerprint='64-char-lowercase-sha256' \
--     -v token_suffix='last6' \
--     -f docs/sql/zsxq_cookie_db_init.sql
--
-- Important:
-- - Do not put plaintext Cookie in this file.
-- - encrypted_cookie must be generated by backend-compatible Fernet code.
-- - cookie_fingerprint must be a sha256 hex digest of the normalized Cookie/token.

\set ON_ERROR_STOP on

\if :{?app_rw_user}
\else
\set app_rw_user cappa_rw
\endif

\if :{?seed_cookie_account}
\else
\set seed_cookie_account false
\endif

\if :{?seed_system_sync_binding}
\else
\set seed_system_sync_binding true
\endif

\if :{?seed_auto_publish_binding}
\else
\set seed_auto_publish_binding true
\endif

\if :{?binding_priority}
\else
\set binding_priority 10
\endif

\if :{?cookie_account_id}
\else
\set cookie_account_id
\endif

\if :{?cookie_account_name}
\else
\set cookie_account_name
\endif

\if :{?cookie_purpose}
\else
\set cookie_purpose both
\endif

\if :{?cookie_group_id}
\else
\set cookie_group_id
\endif

\if :{?encrypted_cookie}
\else
\set encrypted_cookie
\endif

\if :{?cookie_fingerprint}
\else
\set cookie_fingerprint
\endif

\if :{?token_suffix}
\else
\set token_suffix
\endif

BEGIN;

CREATE TABLE IF NOT EXISTS public.zsxq_cookie_accounts (
    id varchar(36) PRIMARY KEY,
    name varchar(120) NOT NULL,
    purpose varchar(32) NOT NULL DEFAULT 'sync',
    group_id varchar(32),
    encrypted_cookie text NOT NULL,
    cookie_fingerprint varchar(64) NOT NULL,
    token_suffix varchar(16),
    status varchar(24) NOT NULL DEFAULT 'active',
    priority integer NOT NULL DEFAULT 100,
    allowed_group_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
    notes text,
    last_validated_at timestamp without time zone,
    last_used_at timestamp without time zone,
    last_success_at timestamp without time zone,
    last_error_at timestamp without time zone,
    last_error_code varchar(64),
    last_error_message text,
    quota_hit_count integer NOT NULL DEFAULT 0,
    meta jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at timestamp without time zone,
    CONSTRAINT ck_zsxq_cookie_accounts_id
        CHECK (length(trim(id)) BETWEEN 1 AND 36),
    CONSTRAINT ck_zsxq_cookie_accounts_name
        CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_zsxq_cookie_accounts_purpose
        CHECK (purpose IN ('sync', 'publish', 'both')),
    CONSTRAINT ck_zsxq_cookie_accounts_status
        CHECK (status IN ('active', 'disabled', 'expired', 'invalid', 'transient_error')),
    CONSTRAINT ck_zsxq_cookie_accounts_encrypted_cookie
        CHECK (length(trim(encrypted_cookie)) > 0),
    CONSTRAINT ck_zsxq_cookie_accounts_fingerprint
        CHECK (cookie_fingerprint ~ '^[0-9a-f]{64}$')
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_zsxq_cookie_accounts_fingerprint_active
    ON public.zsxq_cookie_accounts (cookie_fingerprint)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS ix_zsxq_cookie_accounts_status
    ON public.zsxq_cookie_accounts (status);

CREATE INDEX IF NOT EXISTS ix_zsxq_cookie_accounts_purpose
    ON public.zsxq_cookie_accounts (purpose);

CREATE INDEX IF NOT EXISTS ix_zsxq_cookie_accounts_group_id
    ON public.zsxq_cookie_accounts (group_id);

CREATE INDEX IF NOT EXISTS ix_zsxq_cookie_accounts_priority
    ON public.zsxq_cookie_accounts (priority);

CREATE TABLE IF NOT EXISTS public.zsxq_runtime_bindings (
    id varchar(36) PRIMARY KEY,
    scope varchar(32) NOT NULL,
    group_id varchar(32),
    cookie_account_id varchar(36) NOT NULL,
    priority integer NOT NULL DEFAULT 100,
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at timestamp without time zone,
    CONSTRAINT ck_zsxq_runtime_bindings_id
        CHECK (length(trim(id)) BETWEEN 1 AND 36),
    CONSTRAINT ck_zsxq_runtime_bindings_scope
        CHECK (scope IN ('system_sync', 'auto_publish', 'manual_sync', 'manual_publish')),
    CONSTRAINT fk_zsxq_runtime_bindings_cookie
        FOREIGN KEY (cookie_account_id)
        REFERENCES public.zsxq_cookie_accounts(id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_zsxq_runtime_bindings_scope_group_priority
    ON public.zsxq_runtime_bindings (scope, (COALESCE(group_id, '')), priority)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS ix_zsxq_runtime_bindings_scope
    ON public.zsxq_runtime_bindings (scope);

CREATE INDEX IF NOT EXISTS ix_zsxq_runtime_bindings_group_id
    ON public.zsxq_runtime_bindings (group_id);

CREATE INDEX IF NOT EXISTS ix_zsxq_runtime_bindings_cookie_account_id
    ON public.zsxq_runtime_bindings (cookie_account_id);

GRANT USAGE ON SCHEMA public TO :app_rw_user;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE public.zsxq_cookie_accounts
    TO :app_rw_user;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE public.zsxq_runtime_bindings
    TO :app_rw_user;

COMMIT;

\if :seed_cookie_account

BEGIN;

WITH input AS (
    SELECT
        COALESCE(
            NULLIF(:'cookie_account_id', ''),
            'acct_' || substring(:'cookie_fingerprint' from 1 for 31)
        )::varchar(36) AS account_id,
        COALESCE(NULLIF(:'cookie_account_name', ''), 'ZSXQ Cookie Account')::varchar(120) AS account_name,
        :'cookie_purpose'::varchar(32) AS purpose,
        NULLIF(:'cookie_group_id', '')::varchar(32) AS group_id,
        :'encrypted_cookie'::text AS encrypted_cookie,
        lower(:'cookie_fingerprint')::varchar(64) AS cookie_fingerprint,
        NULLIF(:'token_suffix', '')::varchar(16) AS token_suffix,
        :'binding_priority'::integer AS binding_priority
),
upserted AS (
    INSERT INTO public.zsxq_cookie_accounts (
        id,
        name,
        purpose,
        group_id,
        encrypted_cookie,
        cookie_fingerprint,
        token_suffix,
        status,
        priority,
        allowed_group_ids,
        updated_at
    )
    SELECT
        account_id,
        account_name,
        purpose,
        group_id,
        encrypted_cookie,
        cookie_fingerprint,
        token_suffix,
        'active',
        binding_priority,
        CASE
            WHEN group_id IS NULL THEN '[]'::jsonb
            ELSE jsonb_build_array(group_id)
        END,
        CURRENT_TIMESTAMP
    FROM input
    ON CONFLICT (cookie_fingerprint)
        WHERE deleted_at IS NULL
    DO UPDATE SET
        name = EXCLUDED.name,
        purpose = EXCLUDED.purpose,
        group_id = EXCLUDED.group_id,
        encrypted_cookie = EXCLUDED.encrypted_cookie,
        token_suffix = EXCLUDED.token_suffix,
        status = 'active',
        priority = EXCLUDED.priority,
        allowed_group_ids = EXCLUDED.allowed_group_ids,
        updated_at = CURRENT_TIMESTAMP,
        deleted_at = NULL
    RETURNING id, group_id
),
binding_scopes AS (
    SELECT 'system_sync'::varchar(32) AS scope
    WHERE :seed_system_sync_binding
    UNION ALL
    SELECT 'auto_publish'::varchar(32) AS scope
    WHERE :seed_auto_publish_binding
)
INSERT INTO public.zsxq_runtime_bindings (
    id,
    scope,
    group_id,
    cookie_account_id,
    priority,
    enabled,
    updated_at
)
SELECT
    substring(scope from 1 for 4) || '_' || substring(md5(upserted.id || ':' || scope || ':' || COALESCE(upserted.group_id, '')) from 1 for 31),
    scope,
    upserted.group_id,
    upserted.id,
    input.binding_priority,
    true,
    CURRENT_TIMESTAMP
FROM upserted
CROSS JOIN input
CROSS JOIN binding_scopes
ON CONFLICT (scope, (COALESCE(group_id, '')), priority)
    WHERE deleted_at IS NULL
DO UPDATE SET
    cookie_account_id = EXCLUDED.cookie_account_id,
    enabled = true,
    updated_at = CURRENT_TIMESTAMP,
    deleted_at = NULL;

COMMIT;

\endif

SELECT
    table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name IN ('zsxq_cookie_accounts', 'zsxq_runtime_bindings')
ORDER BY table_name;

SELECT
    'zsxq_cookie_accounts' AS table_name,
    count(*) AS row_count
FROM public.zsxq_cookie_accounts
UNION ALL
SELECT
    'zsxq_runtime_bindings' AS table_name,
    count(*) AS row_count
FROM public.zsxq_runtime_bindings
ORDER BY table_name;
